// Builds the Prolog knowledge base of the mall (the same text is shipped as prolog/mall.pl).
import { EDGES, NODES } from './mall.js'

export function mallKb(blocked = {}) {
  const lines = []
  lines.push('% Malluminate knowledge base (works with SWI-Prolog and with the in-browser interpreter)')
  lines.push('')
  lines.push('% ---- Facts: walkways between sections ----')
  for (const e of EDGES) lines.push(`${blocked[e.id] ? '% closed: ' : ''}connected(${e.a}, ${e.b}).`)
  lines.push('')
  lines.push('% ---- Facts: what each section is ----')
  for (const n of NODES) lines.push(`section(${n.id}, ${n.type}).`)
  lines.push('')
  lines.push('% ---- Facts: customers and what they like ----')
  lines.push('likes(asha, clothing).')
  lines.push('likes(ben, electronics).')
  lines.push('likes(chen, cinema).')
  lines.push('likes(dia, books).')
  lines.push('')
  lines.push('% ---- Rules: walkways work in both directions ----')
  lines.push('link(A, B) :- connected(A, B).')
  lines.push('link(A, B) :- connected(B, A).')
  lines.push('')
  lines.push('% ---- Rules: depth-first path (follows one branch until it must backtrack) ----')
  lines.push('path(A, B, Path) :- walk(A, B, [A], Rev), reverse(Rev, Path).')
  lines.push('walk(B, B, Visited, Visited).')
  lines.push('walk(A, B, Visited, Path) :-')
  lines.push('    link(A, N), \\+ member(N, Visited),')
  lines.push('    walk(N, B, [N|Visited], Path).')
  lines.push('')
  lines.push('% ---- Rules: breadth-first shortest path (fewest walkways) ----')
  lines.push('shortest_path(A, B, Path) :- bfs([[A]], B, [A], Rev), reverse(Rev, Path).')
  lines.push('bfs([[B|T]|_], B, _, [B|T]).')
  lines.push('bfs([[N|T]|Queue], B, Seen, Path) :-')
  lines.push('    findall(M, (link(N, M), \\+ member(M, Seen)), Ms),')
  lines.push('    findall([M, N|T], member(M, Ms), New),')
  lines.push('    append(Queue, New, Queue2),')
  lines.push('    append(Ms, Seen, Seen2),')
  lines.push('    bfs(Queue2, B, Seen2, Path).')
  lines.push('')
  lines.push('% ---- Rules: simple AI-style reasoning ----')
  lines.push('reachable(A, B) :- shortest_path(A, B, _).')
  lines.push('suggest(Person, Store, Route) :- likes(Person, Store), shortest_path(entrance, Store, Route).')
  lines.push('hops(A, B, N) :- shortest_path(A, B, P), length(P, L), N is L - 1.')
  lines.push('crowd_level(N, low) :- N < 35.')
  lines.push('crowd_level(N, medium) :- N >= 35, N < 65.')
  lines.push('crowd_level(N, high) :- N >= 65.')
  lines.push('discounted(Price, Percent, Final) :- Final is Price * (100 - Percent) / 100.')
  return lines.join('\n') + '\n'
}
